create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  role text not null default 'customer' check (role in ('customer', 'admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  product_code integer unique,
  name text not null,
  slug text unique,
  category text,
  description text,
  price numeric(10,2) not null default 0 check (price >= 0),
  price_unit numeric(10,2),
  price_dozen numeric(10,2),
  price_quarter numeric(10,2),
  images jsonb not null default '[]'::jsonb,
  stock integer not null default 0 check (stock >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete set null,
  customer_name text,
  customer_email text,
  customer_phone text,
  delivery_address text,
  status text not null default 'pending'
    check (status in ('pending','confirmed','preparing','shipped','delivered','cancelled')),
  subtotal numeric(10,2) not null default 0 check (subtotal >= 0),
  discount numeric(10,2) not null default 0 check (discount >= 0),
  total numeric(10,2) not null default 0 check (total >= 0),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_code integer,
  product_name text not null,
  size text,
  color text,
  quantity integer not null check (quantity > 0),
  unit_price numeric(10,2) not null check (unit_price >= 0),
  line_total numeric(10,2) generated always as (quantity * unit_price) stored,
  created_at timestamptz not null default now()
);

create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  phone text,
  subject text,
  message text not null,
  status text not null default 'new' check (status in ('new','read','answered','closed')),
  created_at timestamptz not null default now()
);

create table if not exists public.claims (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  customer_name text not null,
  customer_email text not null,
  document_type text,
  document_number text,
  order_reference text,
  claim_type text not null check (claim_type in ('claim','complaint')),
  details text not null,
  request text,
  status text not null default 'received'
    check (status in ('received','in_review','resolved','rejected')),
  created_at timestamptz not null default now()
);

create or replace function public.is_marbellin_admin()
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'admin'
  );
$$;

revoke all on function public.is_marbellin_admin() from public;
grant execute on function public.is_marbellin_admin() to authenticated;

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', ''))
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_marbellin on auth.users;
create trigger on_auth_user_created_marbellin
after insert on auth.users
for each row execute procedure public.handle_new_user();

alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.contact_messages enable row level security;
alter table public.claims enable row level security;

drop policy if exists "Profiles: read own or admin" on public.profiles;
create policy "Profiles: read own or admin" on public.profiles
for select to authenticated using (id = (select auth.uid()) or public.is_marbellin_admin());

-- Los clientes no pueden modificar el campo role desde el cliente.
-- El rol de administrador se asigna exclusivamente desde el SQL Editor.
drop policy if exists "Profiles: update own non-role fields" on public.profiles;
create policy "Profiles: update own non-role fields" on public.profiles
for update to authenticated
using (id = (select auth.uid()) or public.is_marbellin_admin())
with check (id = (select auth.uid()) or public.is_marbellin_admin());

drop policy if exists "Products: public reads active products" on public.products;
create policy "Products: public reads active products" on public.products
for select to anon, authenticated using (active = true or public.is_marbellin_admin());

drop policy if exists "Products: admins manage" on public.products;
create policy "Products: admins manage" on public.products
for all to authenticated using (public.is_marbellin_admin())
with check (public.is_marbellin_admin());

drop policy if exists "Orders: owner or admin reads" on public.orders;
create policy "Orders: owner or admin reads" on public.orders
for select to authenticated using (user_id = (select auth.uid()) or public.is_marbellin_admin());

drop policy if exists "Orders: customer creates own" on public.orders;
create policy "Orders: customer creates own" on public.orders
for insert to authenticated with check (user_id = (select auth.uid()) or public.is_marbellin_admin());

drop policy if exists "Orders: admins update" on public.orders;
create policy "Orders: admins update" on public.orders
for update to authenticated using (public.is_marbellin_admin())
with check (public.is_marbellin_admin());

drop policy if exists "Order items: owner or admin reads" on public.order_items;
create policy "Order items: owner or admin reads" on public.order_items
for select to authenticated using (
  public.is_marbellin_admin() or exists (
    select 1 from public.orders o
    where o.id = order_id and o.user_id = (select auth.uid())
  )
);

drop policy if exists "Order items: owner creates items" on public.order_items;
create policy "Order items: owner creates items" on public.order_items
for insert to authenticated with check (
  public.is_marbellin_admin() or exists (
    select 1 from public.orders o
    where o.id = order_id and o.user_id = (select auth.uid())
  )
);

drop policy if exists "Contact messages: public can submit" on public.contact_messages;
create policy "Contact messages: public can submit" on public.contact_messages
for insert to anon, authenticated with check (status = 'new');

drop policy if exists "Contact messages: admins manage" on public.contact_messages;
create policy "Contact messages: admins manage" on public.contact_messages
for all to authenticated using (public.is_marbellin_admin())
with check (public.is_marbellin_admin());

drop policy if exists "Claims: customer submits" on public.claims;
create policy "Claims: customer submits" on public.claims
for insert to anon, authenticated
with check (status = 'received' and (user_id is null or user_id = (select auth.uid())));

drop policy if exists "Claims: owner or admin reads" on public.claims;
create policy "Claims: owner or admin reads" on public.claims
for select to authenticated using (user_id = (select auth.uid()) or public.is_marbellin_admin());

drop policy if exists "Claims: admins update" on public.claims;
create policy "Claims: admins update" on public.claims
for update to authenticated using (public.is_marbellin_admin())
with check (public.is_marbellin_admin());

grant select on public.products to anon, authenticated;
grant select, insert, update on public.profiles to authenticated;
grant select, insert, update on public.orders to authenticated;
grant select, insert on public.order_items to authenticated;
grant insert on public.contact_messages to anon, authenticated;
grant select, insert, update on public.contact_messages to authenticated;
grant select, insert, update on public.claims to anon, authenticated;

