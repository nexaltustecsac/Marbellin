create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  role text not null default 'customer' check (role in ('customer', 'admin')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  product_code integer unique,
  name text not null,
  slug text unique,
  category text,
  description text,
  price numeric(10,2) not null default 0 check (price >= 0),
  price_unit numeric(10,2),
  price_dozen numeric(10,2),
  price_quarter numeric(10,2),
  images jsonb not null default '[]'::jsonb,
  stock integer not null default 0 check (stock >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete set null,
  customer_name text,
  customer_email text,
  customer_phone text,
  delivery_address text,
  status text not null default 'pending'
    check (status in ('pending','confirmed','preparing','shipped','delivered','cancelled')),
  subtotal numeric(10,2) not null default 0 check (subtotal >= 0),
  discount numeric(10,2) not null default 0 check (discount >= 0),
  total numeric(10,2) not null default 0 check (total >= 0),
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_code integer,
  product_name text not null,
  size text,
  color text,
  quantity integer not null check (quantity > 0),
  unit_price numeric(10,2) not null check (unit_price >= 0),
  line_total numeric(10,2) generated always as (quantity * unit_price) stored,
  created_at timestamptz not null default now()
);

create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  phone text,
  subject text,
  message text not null,
  status text not null default 'new' check (status in ('new','read','answered','closed')),
  created_at timestamptz not null default now()
);

create table if not exists public.claims (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  customer_name text not null,
  customer_email text not null,
  document_type text,
  document_number text,
  order_reference text,
  claim_type text not null check (claim_type in ('claim','complaint')),
  details text not null,
  request text,
  status text not null default 'received'
    check (status in ('received','in_review','resolved','rejected')),
  created_at timestamptz not null default now()
);


