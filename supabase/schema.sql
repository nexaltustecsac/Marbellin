drop policy if exists "Profiles: read own or admin" on public.profiles;
create policy "Profiles: read own or admin" on public.profiles
for select to authenticated using (id = (select auth.uid()) or public.is_marbellin_admin());

-- No se permite actualizar perfiles desde el cliente normal.
-- El rol de administrador se asigna exclusivamente desde SQL Editor.
drop policy if exists "Profiles: update own non-role fields" on public.profiles;
drop policy if exists "Profiles: admins update" on public.profiles;
create policy "Profiles: admins update" on public.profiles
for update to authenticated
using (public.is_marbellin_admin())
with check (public.is_marbellin_admin());

drop policy if exists "Products: public reads active products" on public.products;
create policy "Products: public reads active products" on public.products
for select to anon, authenticated using (active = true or public.is_marbellin_admin());

drop policy if exists "Products: admins manage" on public.products;
create policy "Products: admins manage" on public.products
for all to authenticated using (public.is_marbellin_admin())
with check (public.is_marbellin_admin());

drop policy if exists "Orders: owner or admin reads" on public.orders;
create policy "Orders: owner or admin reads" on public.orders
for select to authenticated using (user_id = (select auth.uid()) or public.is_marbellin_admin());

drop policy if exists "Orders: customer creates own" on public.orders;
create policy "Orders: customer creates own" on public.orders
for insert to authenticated with check (user_id = (select auth.uid()) or public.is_marbellin_admin());

drop policy if exists "Orders: admins update" on public.orders;
create policy "Orders: admins update" on public.orders
for update to authenticated using (public.is_marbellin_admin())
